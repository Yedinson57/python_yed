# asignamos valores
x = 3
y = 2

# establecemos el condicional if-else para saber el numero mayor
if x > y:
    # en caso de que x sea mayor mostramos el siguiente resultado
    print(f"{x} es mayor que {y}")
else:
    # en caso de que y sea mayor mostramos el siguiente resultado
    print(f"{y} es mayor que {x}")
