# asignamos valor
x = 2

# establecemos el condicional if-else para saber si el valor ingresado es par
if x % 2 != 0:
    # en caso de no ser par imprimimos el siguiente resultado
    print(f"El numero {x} no es par")
else:
    # en caso de que sea par imprimimos el siguiente resultado
    print(f"El numero {x} es par")